import { z } from "zod";

/**
 * The survey definition: the JSON document an admin builds and that the public form renders.
 * This schema is the single source of truth for what a valid survey is. The builder, the
 * public form and the API all use it, so they can never disagree.
 */

export const QUESTION_TYPES = ["text", "single_choice", "multi_choice", "rating"] as const;
export type QuestionType = (typeof QUESTION_TYPES)[number];

/** UI names follow the brief: "Multiple Choice (single select)" and "Checkbox (multi-select)". */
export const QUESTION_TYPE_LABELS: Record<QuestionType, string> = {
  text: "Text input",
  single_choice: "Multiple choice",
  multi_choice: "Checkboxes",
  rating: "Rating (1–5)",
};

export const RATING_MIN = 1;
export const RATING_MAX = 5;

export const LIMITS = {
  surveyTitle: 200,
  surveyDescription: 2000,
  questions: 100,
  questionTitle: 300,
  options: 30,
  optionLabel: 200,
  textAnswer: 5000,
} as const;

export const CONDITION_OPERATORS = ["equals", "not_equals", "includes", "not_includes", "gte", "lte"] as const;
export type ConditionOperator = (typeof CONDITION_OPERATORS)[number];

/** Which operators make sense for each source question type. Text answers can't drive conditions. */
export const OPERATORS_BY_SOURCE_TYPE: Record<QuestionType, readonly ConditionOperator[]> = {
  text: [],
  single_choice: ["equals", "not_equals"],
  multi_choice: ["includes", "not_includes"],
  rating: ["equals", "not_equals", "gte", "lte"],
};

// IDs are generated by the builder and never change, so renaming or reordering
// questions/options doesn't break conditions or analytics that reference them.
const idSchema = z.string().regex(/^[\w-]{1,64}$/, "Invalid id");

const optionSchema = z.object({
  id: idSchema,
  label: z.string().trim().min(1, "Option label is required").max(LIMITS.optionLabel),
});

const conditionSchema = z.object({
  questionId: idSchema,
  operator: z.enum(CONDITION_OPERATORS),
  value: z.union([z.string().min(1), z.number()]),
});

const questionBase = {
  id: idSchema,
  title: z.string().trim().min(1, "Question text is required").max(LIMITS.questionTitle),
  required: z.boolean(),
  showIf: conditionSchema.optional(),
};

const choiceOptions = z
  .array(optionSchema)
  .min(2, "Add at least two options")
  .max(LIMITS.options, `At most ${LIMITS.options} options`);

export const questionSchema = z.discriminatedUnion("type", [
  z.object({ ...questionBase, type: z.literal("text") }),
  z.object({ ...questionBase, type: z.literal("single_choice"), options: choiceOptions }),
  z.object({ ...questionBase, type: z.literal("multi_choice"), options: choiceOptions }),
  z.object({ ...questionBase, type: z.literal("rating") }),
]);

const surveyShape = z.object({
  title: z.string().trim().min(1, "Survey title is required").max(LIMITS.surveyTitle),
  description: z.string().trim().max(LIMITS.surveyDescription),
  questions: z.array(questionSchema).max(LIMITS.questions, `At most ${LIMITS.questions} questions`),
});

export const surveyDefinitionSchema = surveyShape.superRefine((survey, ctx) => {
  for (const issue of findReferenceIssues(survey.questions)) {
    ctx.addIssue({ code: "custom", ...issue });
  }
});

export type SurveyDefinition = z.infer<typeof surveyDefinitionSchema>;
export type Question = z.infer<typeof questionSchema>;
export type ChoiceQuestion = Extract<Question, { type: "single_choice" | "multi_choice" }>;
export type Condition = z.infer<typeof conditionSchema>;
export type QuestionOption = z.infer<typeof optionSchema>;

/** A cleaned answer: text → string, single choice → option id, checkboxes → option ids, rating → 1–5. */
export type AnswerValue = string | string[] | number;
export type Answers = Record<string, AnswerValue>;

export const createEmptySurvey = (): SurveyDefinition => ({
  title: "Untitled survey",
  description: "",
  questions: [],
});

interface ReferenceIssue {
  path: (string | number)[];
  message: string;
}

/** Cross-field rules a per-field schema can't express: unique ids and valid conditions. */
function findReferenceIssues(questions: readonly Question[]): ReferenceIssue[] {
  const issues: ReferenceIssue[] = [];
  const indexById = new Map<string, number>();

  questions.forEach((question, i) => {
    if (indexById.has(question.id)) {
      issues.push({ path: ["questions", i, "id"], message: "Duplicate question id" });
    } else {
      indexById.set(question.id, i);
    }

    if (question.type === "single_choice" || question.type === "multi_choice") {
      const seen = new Set<string>();
      question.options.forEach((option, j) => {
        if (seen.has(option.id)) {
          issues.push({ path: ["questions", i, "options", j, "id"], message: "Duplicate option id" });
        }
        seen.add(option.id);
      });
    }
  });

  questions.forEach((question, i) => {
    if (!question.showIf) return;
    const problem = findConditionProblem(question.showIf, i, questions, indexById);
    if (problem) {
      issues.push({ path: ["questions", i, "showIf", problem.field], message: problem.message });
    }
  });

  return issues;
}

function findConditionProblem(
  condition: Condition,
  questionIndex: number,
  questions: readonly Question[],
  indexById: ReadonlyMap<string, number>,
): { field: keyof Condition; message: string } | null {
  const sourceIndex = indexById.get(condition.questionId);
  if (sourceIndex === undefined) {
    return { field: "questionId", message: "This condition refers to a question that no longer exists" };
  }
  // Only allowing backward references makes cycles (A depends on B depends on A) impossible,
  // and lets visibility be computed in a single top-to-bottom pass.
  if (sourceIndex >= questionIndex) {
    return { field: "questionId", message: "A condition can only depend on an earlier question" };
  }

  const source = questions[sourceIndex];
  if (!OPERATORS_BY_SOURCE_TYPE[source.type].includes(condition.operator)) {
    return { field: "operator", message: "This operator doesn't apply to that question type" };
  }

  if (source.type === "rating") {
    const { value } = condition;
    const isValidRating =
      typeof value === "number" && Number.isInteger(value) && value >= RATING_MIN && value <= RATING_MAX;
    return isValidRating ? null : { field: "value", message: "Pick a rating from 1 to 5" };
  }

  // Text sources were already rejected above (they allow no operators), so this is a choice question.
  const isKnownOption = source.type !== "text" && source.options.some((o) => o.id === condition.value);
  return isKnownOption ? null : { field: "value", message: "Pick one of the source question's options" };
}
